"""Generate the aar.library call headers from client/fd/aar_lib.fd.

Writes, under client/include:

  clib/aar_protos.h        C prototypes
  pragmas/aar_pragmas.h    SAS/C style pragmas (not seen by GCC)
  inline/aar.h             GCC m68k inline callers, in the style of the
                           zz9k.library and mpega.library headers
  proto/aar.h              the header a program includes

The .fd file is the only source. Each entry has a "* C:" line with its C
prototype just before it, and the generator checks that the prototype names the
same parameters, in the same order, as the entry's register list. Nothing else
is hand written.

  fdgen.py            write the four headers
  fdgen.py --check    write nothing; exit 1 if a committed header differs
                      from what the .fd file generates, or if the .fd file is
                      malformed
"""

import argparse
import difflib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]  # client/
FD = ROOT / "fd" / "aar_lib.fd"
INCLUDE = ROOT / "include"

LIB_BASE = "AARBase"          # the library base variable
FIRST_LVO = 30                # ##bias
LVO_STEP = 6

REGS = ["d0", "d1", "d2", "d3", "d4", "d5", "d6", "d7",
        "a0", "a1", "a2", "a3", "a4", "a5"]
REG_CODE = {r: format(i, "X") for i, r in enumerate(REGS)}
SCRATCH = ["d1", "a0", "a1"]  # d0 is the result; these are the other scratch registers

BANNER = ("Generated by client/tools/fdgen.py from client/fd/aar_lib.fd. "
          "Do not edit;\n * change the .fd file and run the generator.")


class FdError(Exception):
    pass


class Func:
    def __init__(self, name, lvo, ret, params):
        self.name = name
        self.lvo = lvo              # positive: the vector is at -lvo
        self.ret = ret              # C return type
        self.params = params        # list of (ctype, name, reg)

    @property
    def tag_list(self):
        """A call that takes a tag list gets a varargs companion (SetTags)."""
        return (self.name.endswith("TagList") and self.params
                and self.params[-1][1] == "tags")

    @property
    def tags_name(self):
        return self.name[:-len("TagList")] + "Tags"


def split_param(text):
    """'const char *path' -> ('const char *', 'path')."""
    match = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)$", text.strip())
    if not match or not match.group(1).strip():
        raise FdError("cannot split parameter %r" % text)
    return " ".join(match.group(1).split()), match.group(2)


def parse_proto(text):
    match = re.match(r"^(.*?)\b([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", text)
    if not match:
        raise FdError("bad C prototype %r" % text)
    ret = match.group(1).strip()
    name = match.group(2)
    args = match.group(3).strip()
    params = [] if args in ("", "void") else [split_param(a) for a in args.split(",")]
    return ret, name, params


def parse_fd(text):
    base = None
    bias = None
    public = True
    pending = None
    funcs = []
    ended = False
    for number, raw in enumerate(text.split("\n"), 1):
        line = raw.strip()
        if not line:
            continue
        where = "%s:%d" % (FD.name, number)
        if ended:
            raise FdError("%s: text after ##end" % where)
        if line.startswith("##"):
            words = line[2:].split()
            if words[0] == "base" and len(words) == 2:
                base = words[1]
            elif words[0] == "bias" and len(words) == 2:
                bias = int(words[1])
            elif words[0] == "public":
                public = True
            elif words[0] == "end":
                ended = True
            else:
                raise FdError("%s: unknown command %r" % (where, line))
            continue
        if line.startswith("*"):
            match = re.match(r"^\*\s*C:\s*(.+)$", line)
            if match:
                if pending is not None:
                    raise FdError("%s: two C lines in a row" % where)
                pending = match.group(1).strip()
            continue
        if base is None or bias is None:
            raise FdError("%s: entry before ##base and ##bias" % where)
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\(([^)]*)\)\(([^)]*)\)$", line)
        if not match:
            raise FdError("%s: bad entry %r" % (where, line))
        name = match.group(1)
        names = [n for n in match.group(2).split(",") if n]
        regs = [r for r in match.group(3).split("/") if r]
        if len(names) != len(regs):
            raise FdError("%s: %s has %d names and %d registers" %
                          (where, name, len(names), len(regs)))
        for reg in regs:
            if reg not in REG_CODE:
                raise FdError("%s: %s: register %r cannot carry an argument" %
                              (where, name, reg))
        if len(set(regs)) != len(regs):
            raise FdError("%s: %s: a register is used twice" % (where, name))
        if pending is None:
            raise FdError("%s: %s has no '* C:' prototype line" % (where, name))
        ret, pname, params = parse_proto(pending)
        pending = None
        if pname != name:
            raise FdError("%s: C prototype names %s, entry names %s" %
                          (where, pname, name))
        if [p[1] for p in params] != names:
            raise FdError("%s: %s: C parameters %s differ from the entry's %s" %
                          (where, name, [p[1] for p in params], names))
        lvo = bias + LVO_STEP * len(funcs)
        funcs.append(Func(name, lvo, ret,
                          [(t, n, r) for (t, n), r in zip(params, regs)]))
    if base != "_" + LIB_BASE:
        raise FdError("##base is %r, expected %r" % (base, "_" + LIB_BASE))
    if bias != FIRST_LVO:
        raise FdError("##bias is %r, expected %d" % (bias, FIRST_LVO))
    if not ended:
        raise FdError("missing ##end")
    if pending is not None:
        raise FdError("a '* C:' line has no entry after it")
    names = [f.name for f in funcs]
    if len(set(names)) != len(names):
        raise FdError("duplicate function name")
    return funcs


# ---- Generators --------------------------------------------------------------

def declare(ctype, name):
    """'AARInfo *' and 'info' -> 'AARInfo *info'; 'ULONG', 'n' -> 'ULONG n'."""
    return "%s%s" % (ctype if ctype.endswith("*") else ctype + " ", name)


def decl(func, name=None):
    params = ", ".join(declare(t, n) for t, n, _ in func.params) or "void"
    return "%s %s(%s)" % (func.ret, name or func.name, params)


def gen_clib(funcs):
    out = []
    out.append("/*\n * C prototypes for aar.library.\n *\n * " + BANNER +
               "\n *\n * SPDX-License-Identifier: MIT\n */\n")
    out.append("#ifndef CLIB_AAR_PROTOS_H\n#define CLIB_AAR_PROTOS_H\n")
    out.append("#include <exec/types.h>\n#include <exec/ports.h>\n"
               "#include <utility/tagitem.h>\n#include <libraries/aar.h>\n")
    out.append("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
    for f in funcs:
        out.append(decl(f) + ";")
        if f.tag_list:
            fixed = ", ".join(declare(t, n) for t, n, _ in f.params[:-1])
            out.append("LONG %s(%s, Tag tag1, ...);" % (f.tags_name, fixed))
    out.append("\n#ifdef __cplusplus\n}\n#endif\n")
    out.append("#endif /* CLIB_AAR_PROTOS_H */\n")
    return "\n".join(out).replace("\n\n\n", "\n\n")


def gen_pragmas(funcs):
    out = []
    out.append("/*\n * SAS/C style pragmas for aar.library.\n *\n * " + BANNER +
               "\n *\n * SPDX-License-Identifier: MIT\n */\n")
    out.append("#ifndef PRAGMAS_AAR_PRAGMAS_H\n#define PRAGMAS_AAR_PRAGMAS_H\n")
    out.append("#ifndef CLIB_AAR_PROTOS_H\n#include <clib/aar_protos.h>\n#endif\n")
    out.append("#ifndef __GNUC__")
    for f in funcs:
        # Registers of the arguments in reverse order, a 0, then the count.
        regs = "".join(REG_CODE[r] for _, _, r in reversed(f.params))
        code = "%s0%d" % (regs, len(f.params))
        out.append("#pragma libcall %s %s %03X %s" % (LIB_BASE, f.name, f.lvo, code))
        if f.tag_list:
            out.append("#pragma tagcall %s %s %03X %s" %
                       (LIB_BASE, f.tags_name, f.lvo, code))
    out.append("#endif\n")
    out.append("#endif /* PRAGMAS_AAR_PRAGMAS_H */\n")
    return "\n".join(out)


def inline_one(f):
    regs = {r: (t, n) for t, n, r in f.params}
    lines = []
    sig = ", ".join(declare(t, n) for t, n, _ in f.params) or "void"
    lines.append("static __inline %s __%sInline(%s)" % (f.ret, f.name, sig))
    lines.append("{")
    if "d0" in regs:
        lines.append("  register %s aar_d0 __asm(\"d0\") = %s;" %
                     (regs["d0"][0], regs["d0"][1]))
    else:
        lines.append("  register %s aar_d0 __asm(\"d0\");" % f.ret)
    lines.append("  register struct Library *aar_a6 __asm(\"a6\") = %s;" % LIB_BASE)
    for t, n, r in f.params:
        if r == "d0":
            continue
        lines.append("  register %s = %s;" %
                     (declare(t, "aar_%s __asm(\"%s\")" % (r, r)), n))
    outputs = ["\"+r\"(aar_d0)" if "d0" in regs else "\"=r\"(aar_d0)"]
    inputs = ["\"r\"(aar_a6)"]
    for _, _, r in f.params:
        if r == "d0":
            continue
        if r in SCRATCH:
            outputs.append("\"+r\"(aar_%s)" % r)
        else:
            inputs.append("\"r\"(aar_%s)" % r)
    clobbers = ["\"cc\"", "\"memory\""] + ["\"%s\"" % r for r in SCRATCH if r not in regs]
    lines.append("  __asm volatile(\"jsr -%d(a6)\"" % f.lvo)
    lines.append("                 : " + ", ".join(outputs))
    lines.append("                 : " + ", ".join(inputs))
    lines.append("                 : " + ", ".join(clobbers) + ");")
    if f.ret == "void":
        pass
    elif "d0" in regs and regs["d0"][0] != f.ret:
        lines.append("  return (%s)aar_d0;" % f.ret)
    else:
        lines.append("  return aar_d0;")
    lines.append("}")
    args = ", ".join(n for _, n, _ in f.params)
    wrapped = ", ".join("(%s)" % n for _, n, _ in f.params)
    lines.append("#define %s(%s) __%sInline(%s)" % (f.name, args, f.name, wrapped))
    if f.tag_list:
        fixed = ", ".join(n for _, n, _ in f.params[:-1])
        lines.append("#define %s(%s, tags...) \\" % (f.tags_name, fixed))
        lines.append("  ({ULONG aar_tags[] = {tags}; \\")
        call_args = ["(%s)" % n for _, n, _ in f.params[:-1]]
        call_args.append("(const struct TagItem *)aar_tags")
        lines.append("    %s(%s);})" % (f.name, ", ".join(call_args)))
    return "\n".join(lines)


def gen_inline(funcs):
    out = []
    out.append("/*\n * GCC inline callers for aar.library (AmigaOS m68k).\n *\n * " + BANNER +
               "\n *\n * SPDX-License-Identifier: MIT\n */\n")
    out.append("#ifndef INLINE_AAR_H\n#define INLINE_AAR_H\n")
    out.append("#include <exec/libraries.h>\n#include <libraries/aar.h>\n")
    out.append("#if defined(__GNUC__) && (defined(__amigaos__) || defined(__amiga__) || \\\n"
               "    defined(__AMIGA__))\n")
    out.append("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
    out.append("extern struct Library *%s;\n" % LIB_BASE)
    out.append("\n\n".join(inline_one(f) for f in funcs))
    out.append("\n#ifdef __cplusplus\n}\n#endif\n")
    out.append("#endif /* __GNUC__ && AmigaOS */\n")
    out.append("#endif /* INLINE_AAR_H */\n")
    return "\n".join(out)


def gen_proto(funcs):
    out = []
    out.append("/*\n * The header a program includes to call aar.library.\n *\n * " + BANNER +
               "\n *\n * SPDX-License-Identifier: MIT\n */\n")
    out.append("#ifndef PROTO_AAR_H\n#define PROTO_AAR_H\n")
    out.append("#include <exec/types.h>\n#include <exec/libraries.h>\n")
    out.append("extern struct Library *%s;\n" % LIB_BASE)
    out.append("#include <clib/aar_protos.h>\n#include <pragmas/aar_pragmas.h>\n"
               "#include <inline/aar.h>\n")
    out.append("#endif /* PROTO_AAR_H */\n")
    return "\n".join(out)


GENERATED = [
    ("clib/aar_protos.h", gen_clib),
    ("pragmas/aar_pragmas.h", gen_pragmas),
    ("inline/aar.h", gen_inline),
    ("proto/aar.h", gen_proto),
]


def generate(funcs):
    return {name: fn(funcs) for name, fn in GENERATED}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed headers differ from the .fd file")
    parser.add_argument("--fd", type=pathlib.Path, default=FD)
    parser.add_argument("--include", type=pathlib.Path, default=INCLUDE,
                        help="the include directory the headers live in")
    args = parser.parse_args(argv)

    try:
        funcs = parse_fd(args.fd.read_text(encoding="utf-8"))
    except FdError as error:
        print("fdgen: %s" % error, file=sys.stderr)
        return 1
    files = generate(funcs)

    if args.check:
        bad = 0
        for name, text in files.items():
            path = args.include / name
            have = path.read_bytes().decode("utf-8") if path.exists() else None
            if have != text:
                bad += 1
                print("fdgen: %s is not up to date with %s" % (path, args.fd),
                      file=sys.stderr)
                if have is not None:
                    sys.stderr.writelines(difflib.unified_diff(
                        have.splitlines(True), text.splitlines(True),
                        "committed/" + name, "generated/" + name, n=2))
        if bad:
            print("fdgen: run client/tools/fdgen.py and commit the result",
                  file=sys.stderr)
            return 1
        print("fdgen: %d calls, %d headers up to date" % (len(funcs), len(files)))
        return 0

    for name, text in files.items():
        path = args.include / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
